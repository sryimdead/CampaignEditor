"""Точка входа для запуска бэкенда: python run.py

Запускает приложение как пакет app, поэтому относительные импорты работают.
Запуск `python app/main.py` не поддерживается: там нет родительского пакета.
"""

import uvicorn

if __name__ == "__main__":
    uvicorn.run("app.main:app", host="127.0.0.1", port=8000)
